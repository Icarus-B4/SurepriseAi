def get_active_language() -> str:
    """Gibt das aktive Sprachkürzel ('de' oder 'en') zurück."""
    lang = config.get_str("app_language", "system")
    if lang == "system":
        sys_lang = QLocale.system().name()[:2].lower()
        return "de" if sys_lang == "de" else "en"
    return "de" if lang == "de" else "en"


def tr(key: str) -> str:
    """Übersetzt den Schlüssel in die aktive Sprache."""
    active_lang = get_active_language()
    lang_dict = TRANSLATIONS.get(active_lang, TRANSLATIONS["de"])
    return lang_dict.get(key, key)
